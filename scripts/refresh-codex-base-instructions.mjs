#!/usr/bin/env node
/**
 * Refresh Codex's base instructions
 *
 * Codex sends a model it has no metadata for its own `prompt.md` as the base
 * instructions (`model_info_from_slug` in `codex-rs/models-manager`). When an
 * agent runs on a Local Models source, Maestro hands Codex a model catalog
 * entry for that model (`src/main/local-models/codex-model-catalog.ts`), and the
 * entry has to carry the same instructions, or the model would be prompted
 * differently from Codex's own fallback. This script vendors that file.
 *
 * Every character outside printable ASCII is written as a `\u` escape, so the
 * generated module holds the upstream text byte for byte while the source file
 * itself carries no em or en dash.
 *
 * Usage: npm run refresh-codex-base-instructions [-- <git ref>]
 *        (default ref: the latest `rust-v*` release tag)
 */

import fs from 'fs';
import path from 'path';
import https from 'https';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT = path.join(
	__dirname,
	'..',
	'src',
	'main',
	'local-models',
	'vendor',
	'codex-base-instructions.ts'
);
const REPO = 'openai/codex';
const PROMPT_PATH = 'codex-rs/models-manager/prompt.md';

function get(url) {
	return new Promise((resolve, reject) => {
		https
			.get(url, { headers: { 'User-Agent': 'maestro-refresh-script' } }, (res) => {
				if (
					res.statusCode &&
					res.statusCode >= 300 &&
					res.statusCode < 400 &&
					res.headers.location
				) {
					resolve(get(res.headers.location));
					return;
				}
				if (res.statusCode !== 200) {
					reject(new Error(`GET ${url} answered ${res.statusCode}`));
					res.resume();
					return;
				}
				let body = '';
				res.setEncoding('utf8');
				res.on('data', (chunk) => (body += chunk));
				res.on('end', () => resolve(body));
			})
			.on('error', reject);
	});
}

async function latestReleaseTag() {
	const releases = JSON.parse(
		await get(`https://api.github.com/repos/${REPO}/releases?per_page=20`)
	);
	const release = releases.find((r) => !r.prerelease && /^rust-v\d/.test(r.tag_name));
	if (!release) throw new Error('No rust-v* release found');
	return release.tag_name;
}

function toTemplateLiteral(text) {
	let out = '';
	for (const char of text) {
		const code = char.codePointAt(0);
		if (char === '\\') out += '\\\\';
		else if (char === '`') out += '\\`';
		else if (char === '$') out += '\\$';
		else if (char === '\n' || char === '\t' || (code >= 0x20 && code < 0x7f)) out += char;
		else if (code > 0xffff) out += `\\u{${code.toString(16)}}`;
		else out += `\\u${code.toString(16).padStart(4, '0')}`;
	}
	return out;
}

const ref = process.argv[2] || (await latestReleaseTag());
const prompt = await get(`https://raw.githubusercontent.com/${REPO}/${ref}/${PROMPT_PATH}`);

const module = `/**
 * Codex's base instructions: the prompt Codex sends a model it has no metadata
 * for. GENERATED by \`scripts/refresh-codex-base-instructions.mjs\`; do not edit.
 *
 * Source: https://github.com/${REPO}/blob/${ref}/${PROMPT_PATH}
 * License: Apache-2.0 (https://github.com/${REPO}/blob/main/LICENSE)
 *
 * Read by \`codexModelCatalog()\`. Characters outside printable ASCII are
 * escaped; the string is the upstream file byte for byte.
 */

/** The upstream ref this text was taken from. */
export const CODEX_BASE_INSTRUCTIONS_REF = '${ref}';

export const CODEX_BASE_INSTRUCTIONS = \`${toTemplateLiteral(prompt)}\`;
`;

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, module, 'utf8');
console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)} from ${ref} (${prompt.length} chars)`);
