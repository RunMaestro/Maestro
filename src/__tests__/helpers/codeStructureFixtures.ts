/** The text of a fixture as a file holds it. */
export function fileText(lines: readonly string[]): string {
	return lines.join('\n');
}

/**
 * A body with `count` lines, for a case that needs a file big enough for an outline
 * to be clearly smaller than the source. The statements are valid in TypeScript and
 * in Python, so one filler serves both.
 */
export function filler(count: number, language: 'typescript' | 'python' = 'typescript'): string[] {
	return Array.from({ length: count }, (_, index) =>
		language === 'python' ? `    value_${index} = ${index}` : `\tconst value${index} = ${index};`
	);
}
